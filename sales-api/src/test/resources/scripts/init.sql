CREATE TABLE TB_CAR (
    vin VARCHAR(255) PRIMARY KEY
);

CREATE TABLE TB_CLIENT (
    cpf VARCHAR(255) PRIMARY KEY
);

CREATE TABLE TB_SALES (
    id UUID PRIMARY KEY,
    client_cpf VARCHAR(255) NOT NULL,
    car_vin VARCHAR(255) UNIQUE NOT NULL,
    registration_date TIMESTAMP NOT NULL,
    CONSTRAINT fk_client FOREIGN KEY (client_cpf) REFERENCES TB_CLIENT(cpf),
    CONSTRAINT fk_car FOREIGN KEY (car_vin) REFERENCES TB_CAR(vin)
);

